/**
 * \defgroup command_layer Уровень команд
 * \brief Описание функций, обеспечивающих связь с логическим уровнем.
 *
 * Протокол допускает отправку запросов с возможностью последующего получения данных от адресата.
 * Для этого в библиотеке предусмотрены функции <code>\link itp_push_request \endlink</code> и
 * <code>\link itp_push_notification \endlink</code>.
 * С их помощью можно ставить команды в очередь исполнения и получать ответ в асинхронном режиме
 * через обработчик. Следует помнить, что библиотека не является потокобезопасной, и все
 * функции должны вызываться последовательно. При этом допускается создание запросов из обработчиков.
 * <br>
 * Для обработки запросов, принятых с других узлов необходимо зарегистрировать команды в корневой
 * структуре узла сети, используя функцию <code>\link itp_register_handler \endlink</code>. После
 * приёма пакета, будет выполнен поиск обработчика и, если он найден, будет возвращено подтверждение.
 * В противном случае библиотека вернёт \c NAK с кодом ошибки <code>\link ITP_ERRC_WRONG_COMMAND \endlink</code>.
 * После подтверждения будет вызван обработчик команды, для отправки ответов предусмотрены функции
 * <code>\link itp_push_response \endlink</code> и <code>\link itp_push_response_for \endlink</code>.
 */

